'use strict';
const assert=require('node:assert/strict');
const shortcuts=require('../ui/shortcut-model.js');
const macros=require('../ui/macros.js');
const event=(key,mods={})=>({key,code:mods.code||key,ctrlKey:!!mods.ctrl,shiftKey:!!mods.shift,altKey:!!mods.alt,metaKey:!!mods.meta,defaultPrevented:false,isComposing:false,repeat:false});
assert.equal(shortcuts.lookup(event('Tab',{ctrl:true}),{}),'nextTab');
assert.equal(shortcuts.lookup(event('Tab',{ctrl:true,shift:true}),{}),'previousTab');
assert.equal(shortcuts.lookup(event('Enter'),{}),'sendInput');
assert.equal(shortcuts.lookup(event('a',{ctrl:true,code:'KeyA'}),{}),'selectOutput');
assert.equal(shortcuts.lookup(event('z',{alt:true,code:'KeyZ'}),{}),'sendLastHistory');
assert.equal(shortcuts.lookup(event('PageDown'),{}),'outputPageDown');
assert.equal(shortcuts.safeChord('A'),null);
assert.equal(shortcuts.safeChord('Ctrl+Shift+A'),'Ctrl+Shift+A');
const moved=shortcuts.assign({},'findOutput','Ctrl+K');
assert.equal(shortcuts.lookup(event('f',{ctrl:true,code:'KeyF'}),moved),null);
assert.equal(shortcuts.lookup(event('k',{ctrl:true,code:'KeyK'}),moved),'findOutput');
const collision=shortcuts.assign(moved,'logging','Ctrl+K');
assert.equal(shortcuts.bindings(collision).findOutput,'');
assert.equal(shortcuts.lookup(event('k',{ctrl:true,code:'KeyK'}),collision),'logging');
assert.equal(new Set(Object.values(shortcuts.bindings(collision)).filter(Boolean)).size,Object.values(shortcuts.bindings(collision)).filter(Boolean).length);
assert.deepEqual(shortcuts.normalizeOverrides({logging:'A',evil:'Ctrl+M',mapWindow:'Ctrl+Y'}),{mapWindow:'Ctrl+Y'});
assert.equal(shortcuts.lookup({...event('k',{ctrl:true,code:'KeyK'}),isComposing:true},collision),null);
assert.equal(shortcuts.lookup({...event('k',{ctrl:true,code:'KeyK'}),repeat:true},collision),null);
const macro={id:'m1',enabled:true,key:'Ctrl+F',scope:{level:'global'},text:'look',mode:'send'};
assert.equal(macros.match(event('f',{ctrl:true,code:'KeyF'}),{reservedCombos:shortcuts.boundCombos({}),inputElement:null},[macro]),null);
assert.deepEqual(macros.match(event('f',{ctrl:true,code:'KeyF'}),{reservedCombos:shortcuts.boundCombos(moved),inputElement:null},[macro])?.commands,['look']);
console.log('shortcut model checks passed.');
